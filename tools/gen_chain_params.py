#!/usr/bin/env python3
"""Emit src/chain_params_gen.{h,c} from module.json's chain_params.

Omega serves get_param("chain_params") itself (v0.6) because the host's
module.json fallback re-serialises only key/name/type/min/max/options and drops
`viz` / `card_script` — the custom widgets and cards would never register.
module.json stays the single source of truth; run this after editing it
(the Makefile and scripts/build_web.sh do)."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
cp = json.load(open(os.path.join(ROOT, "module.json")))["chain_params"]
s = json.dumps(cp, separators=(",", ":"), ensure_ascii=True)
lines = []
for i in range(0, len(s), 100):
    chunk = s[i:i + 100].replace("\\", "\\\\").replace('"', '\\"')
    lines.append('    "%s"' % chunk)
c = ("/* GENERATED by tools/gen_chain_params.py from module.json - do not edit. */\n"
     '#include "chain_params_gen.h"\n\nconst char omega_chain_params[] =\n' + "\n".join(lines) +
     ";\nconst unsigned omega_chain_params_len = %d;\n" % len(s.encode()))
h = ("/* GENERATED by tools/gen_chain_params.py - do not edit. */\n#ifndef OMEGA_CHAIN_PARAMS_GEN_H\n"
     "#define OMEGA_CHAIN_PARAMS_GEN_H\nextern const char omega_chain_params[];\n"
     "extern const unsigned omega_chain_params_len;\n#endif\n")
open(os.path.join(ROOT, "src", "chain_params_gen.c"), "w").write(c)
open(os.path.join(ROOT, "src", "chain_params_gen.h"), "w").write(h)
print("chain_params: %d params, %d bytes" % (len(cp), len(s)))
