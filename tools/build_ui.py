#!/usr/bin/env python3
"""Assemble the shipped UI scripts: canvas.js and cards.js at the module root.

Schwung evaluates each script in its own closure, so src/ui/common.js (the O helpers) is
pasted into both at the /* @@COMMON@@ */ marker. Run after editing src/ui/*.js."""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
common = open(os.path.join(ROOT, "src", "ui", "common.js")).read()
for name in ("canvas.js", "cards.js"):
    src = open(os.path.join(ROOT, "src", "ui", name)).read()
    assert "/* @@COMMON@@ */" in src, name
    out = "/* GENERATED by tools/build_ui.py from src/ui/ - edit those, not this. */\n" + \
        src.replace("/* @@COMMON@@ */", common.replace("\n", "\n  ").rstrip())
    open(os.path.join(ROOT, name), "w").write(out)
    print("wrote", name, len(out), "bytes")
